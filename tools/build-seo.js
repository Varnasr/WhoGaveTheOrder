#!/usr/bin/env node
/* =============================================================================
   Search and sharing: static incident pages, head tags, sitemap, robots, cards
   -----------------------------------------------------------------------------
   Everything a crawler or a link preview fetcher needs from the server, because
   neither runs the site's JavaScript.

   An incident page used to be investigation.html?id=<slug>, filled in by the
   browser. To a crawler that was one page with one title, so eighty-six
   incidents shared a single search entry and a single link preview. This writes
   a real page per incident, incident/<slug>.html, with its own title,
   description, canonical link, Open Graph and Twitter tags and JSON-LD. The
   page still loads the same scripts, which replace the static summary with the
   full record, so a reader sees exactly what they saw before.

     incident/<slug>.html   one per incident, from investigation.html
     <seo> block            in the head of every root page, between markers
     sitemap.xml            every indexable page and incident
     robots.txt
     og/cards.json          what each share image must say; og/manifest.json,
                            written by tools/build-og.js, records the hash of
                            what each rendered image was drawn from

       node tools/build-seo.js            write everything
       node tools/build-seo.js --check    fail if anything is stale or missing
   ========================================================================== */

'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { ROOT, load } = require('./archive');

const CHECK = process.argv.includes('--check');
const BEGIN = '<!-- seo:begin (generated by tools/build-seo.js, do not edit) -->';
const END = '<!-- seo:end -->';
const SITE_NAME = 'WhoGaveTheOrder.in';
const CARD_VERSION = 2;

/* Pages that carry a head block but stay out of the index and the sitemap. The
   investigation shell has no incident in it, and a search results page is not a
   document. */
const NOINDEX = new Set(['investigation.html', 'search.html']);

const problems = [];
const writes = new Map();   // relative path -> contents

function main() {
  const WGO = load();
  const siteUrl = String(WGO.config.siteUrl || '').replace(/\/$/, '');
  if (!siteUrl) { throw new Error('config.siteUrl is empty'); }
  const model = WGO.model;

  const rootPages = fs.readdirSync(ROOT).filter((f) => f.endsWith('.html')).sort();
  const cards = [];
  const sitemap = [];

  /* --- incident pages ----------------------------------------------------- */
  const shell = stripSeo(read('investigation.html'));
  for (const inc of model.incidents) {
    const evidence = model.evidenceFor(inc.id);
    const order = model.authorisationStatus(inc.id);
    const description = describe(inc, evidence.length, order && order.established);
    const url = `${siteUrl}/incident/${inc.slug}.html`;
    const image = `${siteUrl}/og/incident-${inc.slug}.png`;
    const title = `${inc.title} | ${SITE_NAME}`;
    const stateLabel = label(inc.incidentState);
    const alt = `${inc.title}. ${inc.place}. Evidence state: ${stateLabel}.`;

    cards.push(card('incident', `incident-${inc.slug}`, {
      title: inc.title,
      line: [inc.date || inc.isoDate, inc.place].filter(Boolean).join('  |  '),
      state: inc.incidentState,
      stateLabel,
      order: order && order.established ? 'An order is on the record' : 'No order has been found',
      count: evidence.length
    }));

    const head = seoBlock({
      type: 'article', title: inc.title, fullTitle: title, description, url, image, alt, siteUrl,
      jsonld: [
        {
          '@context': 'https://schema.org',
          '@type': 'Article',
          headline: inc.title,
          description,
          datePublished: inc.openedOn || inc.isoDate,
          dateModified: inc.openedOn || inc.isoDate,
          inLanguage: 'en-IN',
          mainEntityOfPage: url,
          image,
          author: { '@type': 'Organization', name: SITE_NAME, url: siteUrl + '/' },
          publisher: { '@type': 'Organization', name: SITE_NAME, url: siteUrl + '/' },
          contentLocation: { '@type': 'Place', name: inc.place }
        },
        breadcrumb(siteUrl, [['Home', '/'], ['Investigations', '/investigations.html'], [inc.title, `/incident/${inc.slug}.html`]])
      ]
    });

    writes.set(`incident/${inc.slug}.html`, incidentPage(shell, inc, { title, description, head, stateLabel, evidenceCount: evidence.length }));
    sitemap.push({ loc: url, lastmod: inc.openedOn || inc.isoDate, priority: '0.8' });
  }

  /* --- root pages ---------------------------------------------------------- */
  for (const file of rootPages) {
    const name = file.replace(/\.html$/, '');
    const html = stripSeo(read(file));
    const title = (html.match(/<title>([\s\S]*?)<\/title>/) || [])[1];
    const description = unesc((html.match(/<meta name="description" content="([^"]*)"/) || [])[1] || '');
    if (!title || !description) { problems.push(`${file}: needs a <title> and a meta description`); continue; }

    const isHindi = file === 'hi.html';
    const canonical = file === 'index.html' ? `${siteUrl}/` : `${siteUrl}/${file}`;
    const image = `${siteUrl}/og/${name}.png`;
    const shortTitle = unesc(title).replace(/\s*\|\s*WhoGaveTheOrder\.in$/, '');
    const alt = `${shortTitle}. ${SITE_NAME}`;

    cards.push(card('page', name, { title: file === 'index.html' ? 'Who gave the order?' : shortTitle, line: description, state: null, stateLabel: '', order: '', count: 0 }));

    const jsonld = [{
      '@context': 'https://schema.org',
      '@type': file === 'index.html' ? 'WebSite' : 'WebPage',
      name: shortTitle,
      description,
      url: canonical,
      inLanguage: isHindi ? 'hi-IN' : 'en-IN',
      isPartOf: { '@type': 'WebSite', name: SITE_NAME, url: siteUrl + '/' }
    }];
    if (file === 'index.html') {
      jsonld.push({
        '@context': 'https://schema.org',
        '@type': 'Organization',
        name: SITE_NAME,
        url: siteUrl + '/',
        description: 'A public record of police use of force in India, and the chain of authority behind it.'
      });
    }

    const alternates = (file === 'index.html' || isHindi)
      ? [['en', `${siteUrl}/`], ['hi', `${siteUrl}/hi.html`], ['x-default', `${siteUrl}/`]]
      : [];

    const head = seoBlock({
      type: 'website', title: shortTitle, fullTitle: unesc(title), description, url: canonical, image, alt, siteUrl,
      locale: isHindi ? 'hi_IN' : 'en_IN', alternates, noindex: NOINDEX.has(file), jsonld
    });
    writes.set(file, withSeo(html, head));
    if (!NOINDEX.has(file)) {
      sitemap.push({ loc: canonical, priority: file === 'index.html' ? '1.0' : '0.6' });
    }
  }

  /* the default card, for anything without its own */
  cards.push(card('page', 'default', {
    title: 'Who gave the order?',
    line: 'A public record of police use of force in India, and the chain of authority behind it.',
    state: null, stateLabel: '', order: '', count: 0
  }));

  writes.set('sitemap.xml', sitemapXml(sitemap));
  writes.set('robots.txt', `User-agent: *\nAllow: /\n\nSitemap: ${siteUrl}/sitemap.xml\n`);
  writes.set('og/cards.json', JSON.stringify(cards, null, 2) + '\n');

  finish(cards);
}

/* --- builders ------------------------------------------------------------- */

function describe(inc, count, ordered) {
  const when = [inc.date || inc.isoDate, inc.place].filter(Boolean).join(', ');
  const bits = [
    `${inc.title}.`,
    `${when}.`,
    `${count} sourced evidence item${count === 1 ? '' : 's'} on the record, ${label(inc.incidentState)}.`,
    ordered ? 'An order is on the record.' : 'No order authorising the force has been located.'
  ];
  return bits.join(' ');
}

function label(state) {
  return String(state || '').toLowerCase().replace(/_/g, ' ');
}

function card(kind, name, fields) {
  const spec = Object.assign({ v: CARD_VERSION, kind, name, file: `og/${name}.png` }, fields);
  spec.hash = crypto.createHash('sha1').update(JSON.stringify(spec)).digest('hex').slice(0, 16);
  return spec;
}

function seoBlock(o) {
  const e = esc;
  const desc = clip(o.description, 300);
  const lines = [
    BEGIN,
    `<link rel="canonical" href="${e(o.url)}">`
  ];
  for (const [lang, href] of (o.alternates || [])) {
    lines.push(`<link rel="alternate" hreflang="${lang}" href="${e(href)}">`);
  }
  if (o.noindex) { lines.push('<meta name="robots" content="noindex, follow">'); }
  lines.push(
    `<meta property="og:type" content="${o.type}">`,
    `<meta property="og:site_name" content="${SITE_NAME}">`,
    `<meta property="og:locale" content="${o.locale || 'en_IN'}">`,
    `<meta property="og:title" content="${e(o.title)}">`,
    `<meta property="og:description" content="${e(desc)}">`,
    `<meta property="og:url" content="${e(o.url)}">`,
    `<meta property="og:image" content="${e(o.image)}">`,
    '<meta property="og:image:type" content="image/png">',
    '<meta property="og:image:width" content="1200">',
    '<meta property="og:image:height" content="630">',
    `<meta property="og:image:alt" content="${e(o.alt)}">`,
    '<meta name="twitter:card" content="summary_large_image">',
    `<meta name="twitter:title" content="${e(o.title)}">`,
    `<meta name="twitter:description" content="${e(clip(o.description, 200))}">`,
    `<meta name="twitter:image" content="${e(o.image)}">`,
    `<meta name="twitter:image:alt" content="${e(o.alt)}">`
  );
  for (const doc of o.jsonld || []) {
    lines.push(`<script type="application/ld+json">${JSON.stringify(doc).replace(/</g, '\\u003c')}</script>`);
  }
  lines.push(END);
  return lines.join('\n');
}

function breadcrumb(siteUrl, items) {
  return {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: items.map(([name, p], i) => ({ '@type': 'ListItem', position: i + 1, name, item: siteUrl + p }))
  };
}

function incidentPage(shell, inc, o) {
  let t = shell;
  t = t.replace(/<title>[\s\S]*?<\/title>/, `<title>${esc(o.title)}</title>`);
  t = t.replace(/<meta name="description" content="[^"]*">/, `<meta name="description" content="${esc(clip(o.description, 160))}">`);

  /* Resolve every relative reference against the site root, from one folder
     down. A relative base keeps the page working off the filesystem too. */
  t = t.replace(/(<meta name="viewport"[^>]*>)/, '$1\n<base href="../">');

  /* A base element also redirects fragment-only links, so a skip link would
     leave the page. Anchor them to this page explicitly. */
  t = t.replace(/href="#/g, `href="incident/${inc.slug}.html#`);

  t = t.replace('<body data-page="investigation">', `<body data-page="investigation" data-incident="${esc(inc.slug)}">`);
  t = t.replace(/(<p class="crumb">[\s\S]*?<a href="investigations\.html">Investigations<\/a> \/ )Investigation(<\/p>)/, `$1${esc(inc.title)}$2`);
  t = t.replace('data-region="incident-title">Investigation</h1>', `data-region="incident-title">${esc(inc.title)}</h1>`);
  t = t.replace('<div class="row" data-region="incident-meta"></div>',
    `<div class="row" data-region="incident-meta"><span class="mono">${esc(inc.id)}</span> <span class="mono">${esc(o.stateLabel)}</span> <span class="mono">${esc(inc.place)}</span></div>`);

  /* What a crawler reads. The scripts replace it with the full record. */
  const facts = [
    ['Date', inc.date || inc.isoDate],
    ['Location', `${inc.place}, ${inc.state}`],
    ['Evidence state', o.stateLabel],
    ['Evidence items on the record', String(o.evidenceCount)]
  ].filter((f) => f[1]);
  const staticBody = `<p>${esc(o.description)}</p><ul>` +
    facts.map((f) => `<li>${esc(f[0])}: ${esc(f[1])}</li>`).join('') + '</ul>';
  t = t.replace('<div data-region="what-happened"></div>', `<div data-region="what-happened">${staticBody}</div>`);

  return withSeo(t, o.head);
}

function sitemapXml(entries) {
  const rows = entries.map((e) =>
    '  <url>\n' +
    `    <loc>${xml(e.loc)}</loc>\n` +
    (e.lastmod ? `    <lastmod>${e.lastmod}</lastmod>\n` : '') +
    `    <priority>${e.priority}</priority>\n` +
    '  </url>').join('\n');
  return '<?xml version="1.0" encoding="UTF-8"?>\n' +
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + rows + '\n</urlset>\n';
}

/* --- head handling -------------------------------------------------------- */

function stripSeo(html) {
  let t = html.replace(new RegExp(escapeRe(BEGIN) + '[\\s\\S]*?' + escapeRe(END) + '\\n?'), '');
  /* Anything written by hand before the generator existed. */
  t = t.replace(/^[ \t]*<meta (?:property|name)="(?:og|twitter):[^"]*"[^>]*>\n/gm, '');
  t = t.replace(/^[ \t]*<link rel="canonical"[^>]*>\n/gm, '');
  return t;
}

function withSeo(html, block) {
  if (!/<\/head>/.test(html)) { throw new Error('page has no </head>'); }
  return html.replace('</head>', block + '\n</head>');
}

/* --- finishing ------------------------------------------------------------ */

function finish(cards) {
  /* A card is stale when its image was drawn from different words. */
  let pendingImages = 0;
  const manifestPath = path.join(ROOT, 'og/manifest.json');
  let manifest = {};
  try { manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8')); } catch (err) { /* none yet */ }
  for (const c of cards) {
    const missing = !fs.existsSync(path.join(ROOT, c.file));
    if (missing || manifest[c.name] !== c.hash) {
      const msg = `${c.file}: share image is ${missing ? 'missing' : 'out of date'} (run node tools/build-og.js)`;
      if (CHECK) { problems.push(msg); } else { pendingImages += 1; }
    }
  }
  const known = new Set(cards.map((c) => c.file));
  const ogDir = path.join(ROOT, 'og');
  if (fs.existsSync(ogDir)) {
    for (const f of fs.readdirSync(ogDir)) {
      if (f.endsWith('.png') && !known.has(`og/${f}`)) {
        if (CHECK) { problems.push(`og/${f}: orphan share image, no page uses it`); } else { fs.unlinkSync(path.join(ogDir, f)); }
      }
    }
  }

  /* Every incident the data holds must have a page, and no page may outlive its
     incident. */
  const incidentDir = path.join(ROOT, 'incident');
  const want = new Set([...writes.keys()].filter((k) => k.startsWith('incident/')).map((k) => k.slice(9)));
  if (fs.existsSync(incidentDir)) {
    for (const f of fs.readdirSync(incidentDir)) {
      if (!want.has(f)) {
        if (CHECK) { problems.push(`incident/${f}: no incident has this slug any more`); }
        else { fs.unlinkSync(path.join(incidentDir, f)); }
      }
    }
  }

  let stale = 0;
  for (const [rel, content] of writes) {
    const abs = path.join(ROOT, rel);
    const current = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
    if (current === content) { continue; }
    stale += 1;
    if (CHECK) { problems.push(`${rel}: generated output is stale (run node tools/build-seo.js)`); continue; }
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content);
  }

  /* The things a link preview needs, asserted from the finished pages. */
  for (const [rel, content] of writes) {
    if (!rel.endsWith('.html')) { continue; }
    for (const need of ['rel="canonical"', 'property="og:title"', 'property="og:description"', 'property="og:image"', 'name="twitter:card"', 'application/ld+json']) {
      if (!content.includes(need)) { problems.push(`${rel}: missing ${need}`); }
    }
  }

  if (problems.length) {
    console.error(problems.map((p) => 'FAIL: ' + p).join('\n'));
    console.error(`\n${problems.length} problem(s).`);
    process.exit(1);
  }
  console.log(CHECK
    ? `OK: ${writes.size} generated files match, ${cards.length} share images current.`
    : `Wrote ${stale} file(s); ${writes.size} generated in all, ${cards.length} share images specified` +
      (pendingImages ? `, ${pendingImages} to render with node tools/build-og.js.` : '.'));
}

/* --- small helpers -------------------------------------------------------- */

function read(rel) { return fs.readFileSync(path.join(ROOT, rel), 'utf8'); }
function esc(s) { return String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;'); }
function unesc(s) { return String(s).replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&'); }
function xml(s) { return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;'); }
function escapeRe(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }
function clip(s, n) {
  if (s.length <= n) { return s; }
  /* End on a whole sentence when one fits in the budget. */
  const cut = s.slice(0, n);
  const stop = cut.lastIndexOf('. ');
  if (stop > n * 0.5) { return cut.slice(0, stop + 1); }
  return cut.slice(0, cut.lastIndexOf(' ')).replace(/[,;:.]$/, '') + '\u2026';
}

main();
